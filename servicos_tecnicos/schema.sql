CREATE TABLE IF NOT EXISTS USUARIOS (
    ID SERIAL PRIMARY KEY,
    NOME VARCHAR(120) UNIQUE NOT NULL,
    SENHA VARCHAR(255) NOT NULL,
    ENTRADA DATE NOT NULL DEFAULT CURRENT_DATE,
    PERCURSO_ATIVO INTEGER NULL,
    TIPO CHAR(1) NOT NULL DEFAULT 'U' CHECK (TIPO IN ('U', 'M'))
);

CREATE TABLE IF NOT EXISTS AMIGOS (
    USUARIO1_ID INTEGER NOT NULL REFERENCES USUARIOS(ID) ON DELETE CASCADE,
    USUARIO2_ID INTEGER NOT NULL REFERENCES USUARIOS(ID) ON DELETE CASCADE,
    PRIMARY KEY (USUARIO1_ID, USUARIO2_ID)
);

CREATE TABLE IF NOT EXISTS PEDIDOS_AMIZADE (
    USUARIO1_ID INTEGER NOT NULL REFERENCES USUARIOS(ID) ON DELETE CASCADE,
    USUARIO2_ID INTEGER NOT NULL REFERENCES USUARIOS(ID) ON DELETE CASCADE,
    PRIMARY KEY (USUARIO1_ID, USUARIO2_ID)
);

CREATE TABLE IF NOT EXISTS CONQUISTAS (
    ID SERIAL PRIMARY KEY,
    NOME VARCHAR(120) UNIQUE NOT NULL,
    DESCRICAO VARCHAR(255) NOT NULL
);

CREATE TABLE IF NOT EXISTS CONQUISTAS_USUARIO (
    CONQUISTA_ID INTEGER NOT NULL REFERENCES CONQUISTAS(ID) ON DELETE CASCADE,
    USUARIO_ID INTEGER NOT NULL REFERENCES USUARIOS(ID) ON DELETE CASCADE,
    PRIMARY KEY (CONQUISTA_ID, USUARIO_ID)
);

CREATE TABLE IF NOT EXISTS TRILHAS (
    ID SERIAL PRIMARY KEY,
    NOME VARCHAR(150) UNIQUE NOT NULL,
    LOCAL_INICIO VARCHAR(150) NOT NULL,
    LOCAL_FIM VARCHAR(150) NOT NULL,
    COMPRIMENTO NUMERIC(10, 2) NOT NULL,
    AVALIACAO NUMERIC(4, 2) NOT NULL DEFAULT 0.0,
    DIFICULDADE INTEGER NOT NULL,
    VARIACAO_ALTITUDE INTEGER NOT NULL,
    DURACAO_MEDIA TIME NOT NULL,
    CRIADOR_ID INTEGER NULL REFERENCES USUARIOS(ID) ON DELETE SET NULL,
    APROVADOR_ID INTEGER NULL REFERENCES USUARIOS(ID) ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS REGISTROS (
    ID SERIAL PRIMARY KEY,
    TRILHA_ID INTEGER NOT NULL REFERENCES TRILHAS(ID) ON DELETE CASCADE,
    TEMPO TIME NULL,
    AVALIACAO NUMERIC(4, 2) NULL,
    DIFICULDADE INTEGER NULL,
    TIPO CHAR(1) NOT NULL CHECK (TIPO IN ('I', 'G'))
);

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'fk_usuarios_percurso_ativo'
    ) THEN
        ALTER TABLE USUARIOS
            ADD CONSTRAINT fk_usuarios_percurso_ativo
            FOREIGN KEY (PERCURSO_ATIVO) REFERENCES REGISTROS(ID) ON DELETE SET NULL;
    END IF;
END $$;

CREATE TABLE IF NOT EXISTS REGISTROS_INDIVIDUAL (
    REGISTRO_ID INTEGER PRIMARY KEY REFERENCES REGISTROS(ID) ON DELETE CASCADE,
    USUARIO_ID INTEGER NOT NULL REFERENCES USUARIOS(ID) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS REGISTROS_GRUPO (
    REGISTRO_ID INTEGER NOT NULL REFERENCES REGISTROS(ID) ON DELETE CASCADE,
    USUARIO_ID INTEGER NOT NULL REFERENCES USUARIOS(ID) ON DELETE CASCADE,
    PRIMARY KEY (REGISTRO_ID, USUARIO_ID)
);
